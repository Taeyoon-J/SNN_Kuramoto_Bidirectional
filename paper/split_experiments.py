#!/usr/bin/env python3
"""Generate appendix_experiments.tex (Appendices F and G) for main_full.tex.

    experiments.tex    -> Appendix F, "Additional Experiments"
    supplementary.tex  -> Appendix G, "Supplementary Tables"

main_full.tex is now the master for the main text: the Experiments section lives there
directly, so nothing is generated for it. experiments.tex is kept as the source of the two
subsections that do not fit the four-page main text -- baseline fairness, and rollout length
with data scaling -- because they are long, numeric, and easier to keep correct in one place.
Appendix E (evaluation conditions) is hand-written in appendix_evaluation.tex.

Run after editing experiments.tex or supplementary.tex:

    python3 split_experiments.py

WHY THE APPENDIX AND NOT A SEPARATE SUPPLEMENTARY PDF
Nothing in aaai2027.sty requires either. The appendix is already part of the paper's PDF and
is excluded from the page limit, so keeping this material there means one file, a reviewer who
cannot miss it, and \\ref{tab:main} that resolves -- which it cannot across two documents.

NUMBERING
main_full.tex sets \\setcounter{secnumdepth}{0}, so every heading number is written by hand
here, and any \\ref to an unnumbered heading is replaced by its literal number.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / 'experiments.tex').read_text().split('\n')


def find(prefix):
    for i, line in enumerate(src):
        if line.startswith(prefix):
            return i
    raise SystemExit('anchor not found in experiments.tex: ' + prefix)


i33 = find(r'\subsection{Are the baselines handicapped?}')
i35 = find(r'\subsection{Limitations}')
app = '\n'.join(src[i33:i35])

for a, b in [
    (r'\subsection{Are the baselines handicapped?}',
     '\\subsection{F Additional Experiments}\n'
     '\\subsubsection{F1 Are the baselines handicapped?}'),
    (r'\subsection{Rollout length}', r'\subsubsection{F2 Rollout length and data scaling}'),
    (r'\subsection{Spike timing, measured}', r'\subsubsection{F3 Spike timing, measured}'),
    ('Full figures are in the supplementary\ndocument.', 'Full figures are in Appendix~G.'),
]:
    if a not in app:
        raise SystemExit('appendix substitution anchor missing: ' + repr(a))
    app = app.replace(a, b)

tables = (HERE / 'supplementary.tex').read_text()
# supplementary.tex was written for a standalone document; demote one level so it nests
# inside \section{Appendix} beside A-F.
for a, b in [
    (r'\section{Supplementary Tables}',          r'\subsection{G Supplementary Tables}'),
    (r'\subsection{Released weights}',            r'\subsubsection{G1 Released weights}'),
    (r'\subsection{Training budget per baseline}', r'\subsubsection{G2 Training budget per baseline}'),
    (r'\subsection{Scaling with training data}',  r'\subsubsection{G3 Scaling with training data}'),
]:
    if a not in tables:
        raise SystemExit('tables substitution anchor missing: ' + repr(a))
    tables = tables.replace(a, b)

(HERE / 'appendix_experiments.tex').write_text(
    '% GENERATED by split_experiments.py from experiments.tex and supplementary.tex --\n'
    '% do not edit directly. Appendix F is the two Experiments subsections that do not fit\n'
    '% the four-page main text; Appendix G is the per-model tables.\n%\n'
    + app + '\n\n' + tables)

print('appendix_experiments.tex   %4d lines' % len((app + tables).split('\n')))
for stale in ('experiments_main.tex', 'experiments_numbered.tex', 'supplementary_experiments.tex'):
    p = HERE / stale
    if p.exists():
        p.unlink()
        print('removed stale %s' % stale)
