def _load_admission():
    """Require the exact admitted v2 receipt and freshly rebuilt source proof."""
    from collaborative_test.SW_0167_structured_relation_energy import preflight_queue_v2 as pq
    state = json.loads(PREFLIGHT_STATE.read_text(encoding="utf-8"))
    if state.get("status") != "complete_admitted":
        raise ValueError("SW0167 two-update GPU preflight is not complete_admitted")
    if not PREFLIGHT_REPORT.is_file() or sha256_file(PREFLIGHT_REPORT) != state.get("report_sha256"):
        raise ValueError("SW0167 preflight report does not match terminal queue state")
    audit, prep, prepared, supports, targets, proof = pq._source_admission()
    fp = pq.fingerprint_sha256()
    report = json.loads(PREFLIGHT_REPORT.read_text(encoding="utf-8"))
    pq.validate_report(report, source_proof=proof, fingerprint=fp)
    return audit, prep, prepared, proof, sha256_file(PREFLIGHT_REPORT)


def _open_full_caches():
    """Deep-validate the exact 512-row source/context caches once at entry."""
    source_cache = audit_train_cache.source_cache
    context_cache = audit_train_cache.context_cache
    source_path = source_cache.CACHE_ROOT / "manifest.json"
    context_path = context_cache.CACHE_ROOT / "manifest.json"
    source_manifest = json.loads(source_path.read_text(encoding="utf-8"))
    context_manifest = json.loads(context_path.read_text(encoding="utf-8"))
    source_cache.validate_final_cache(source_cache.CACHE_ROOT,
                                      expected_bindings=source_manifest["bindings"])
    context_cache.validate_final_cache(context_cache.CACHE_ROOT,
                                       expected_bindings=context_manifest["bindings"])
    if source_manifest.get("count") != COUNT or context_manifest.get("count") != COUNT:
        raise ValueError("SW0167 training requires the complete 512-row caches")
    checkpoint, source_file, source_contract, pool_rows, ordered_ids, source_sha = (
        audit_train_cache.sw130.source_contract(SEED))
    if (source_sha != source_manifest["bindings"].get("source_checkpoint_sha256")
            or [int(x) for x in ordered_ids[:COUNT]] != source_manifest["bindings"].get("image_ids")
            or context_manifest["bindings"].get("ordered_image_ids") != [int(x) for x in ordered_ids[:COUNT]]):
        raise ValueError("source/cache ordered ID or checkpoint lineage mismatch")
    rgb_sha = source_manifest["bindings"].get("image_rgb_sha256")
    source = source_cache._AtomicTraceCache(source_cache.CACHE_ROOT,
        source_manifest["bindings"], ordered_ids[:COUNT], rgb_sha)
    context = context_cache.AtomicContextCache(context_cache.CACHE_ROOT,
                                               context_manifest["bindings"])
    if len(source.records) != COUNT or len(context.records) != COUNT:
        raise ValueError("cache loaders did not validate all 512 committed rows")
    return {
        "source": source, "context": context,
        "source_manifest": source_manifest, "context_manifest": context_manifest,
        "source_manifest_sha256": sha256_file(source_path),
        "context_manifest_sha256": sha256_file(context_path),
        "source_file_sha256": sha256_file(source_file),
        "source_manifest_path": str(source_file),
        "source_checkpoint_sha256": source_sha,
        "source_checkpoint_path": str(checkpoint),
        "source_ids": [int(x) for x in ordered_ids[:COUNT]],
        "gain": float(audit_train_cache._load_registered_gain(
            source_sha, sha256_file(source_file))[0]),
        "source_state_sha256": source_manifest["source_model_state_before_sha256"],
    }


def _supports_and_targets(caches):
    """Build fixed source-F and feasible TRAIN targets from original B4 rows."""
    source, context = caches["source"], caches["context"]
    supports, targets = [], []
    for start in range(0, COUNT, 4):
        loaded = [source.load_row(i) for i in range(start, start + 4)]
        batch = np.stack([row[0] for row in loaded])
        q_b4 = audit_train_cache._recompute_cpu_q(batch)
        for offset in range(4):
            index = start + offset
            f = qcc_readout.qcc_labels_from_affinity(q_b4[offset:offset+1])[0].numpy().astype(np.int32)
            _, modal = loaded[offset]
            target32 = np.asarray(modal, dtype=np.int64).reshape(32, 32)
            targets.append(structured_energy.feasible_target(f, target32))
            supports.append(f)
    return np.stack(supports), targets


